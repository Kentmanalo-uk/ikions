/**
 * `pnpm icons:dupes [threshold]` — report exact and near-duplicate icons.
 * Writes docs/duplicates-report.md. Exits non-zero on exact duplicates.
 */
import fs from "node:fs";
import path from "node:path";
import { loadCatalog } from "../catalog.ts";
import { findDuplicates } from "../dupes.ts";
import { ROOT } from "../paths.ts";

const threshold = Number(process.argv[2] ?? 0.9);
const started = Date.now();
const { icons } = loadCatalog();
const { exact, near } = findDuplicates(icons, threshold);

const report = `# Duplicate report

> Generated by \`pnpm icons:dupes\` over ${icons.length} icons (${icons.length * 2} variants), threshold IoU ≥ ${threshold}.
> Near-duplicates compare 32 px masks, including the other icon's rotations and mirrors.
> Pairs whose names differ only by direction or state (up/down, on/off…) are intentional families and are not listed.

## Exact duplicates (${exact.length})

${exact.length ? exact.map((d) => `- \`${d.a}\` and \`${d.b}\` (${d.variant})`).join("\n") : "None."}

## Near-duplicates for review (${near.length})

| Icon A | Icon B | Variant | Similarity | Match |
| --- | --- | --- | ---: | --- |
${near.map((d) => `| ${d.a} | ${d.b} | ${d.variant} | ${d.score} | ${d.transform} |`).join("\n")}
`;
fs.writeFileSync(path.join(ROOT, "docs", "duplicates-report.md"), report);
console.log(`${exact.length} exact, ${near.length} near-duplicate pair(s) ≥ ${threshold} in ${((Date.now() - started) / 1000).toFixed(1)}s → docs/duplicates-report.md`);
for (const d of near.slice(0, 40)) console.log(`  ${d.score}  ${d.a} ~ ${d.b} (${d.variant}, ${d.transform})`);
if (exact.length) process.exit(1);

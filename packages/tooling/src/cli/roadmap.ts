/**
 * Catalog roadmap report. Compares assets/roadmap.json (planned concepts)
 * with assets/source (published icons) and writes docs/catalog-roadmap.md.
 * Planned concepts are never counted as published.
 */
import fs from "node:fs";
import path from "node:path";
import { loadCatalog, readJson } from "../catalog.ts";
import { ASSETS, ROOT } from "../paths.ts";
import { NAME_PATTERN } from "../schema.ts";

interface Roadmap {
  categories: Record<string, string[]>;
}

const roadmap = readJson<Roadmap>(path.join(ASSETS, "roadmap.json"));
const { icons, categories } = loadCatalog();
const published = new Map(icons.map((i) => [i.meta.name, i.meta]));
const aliasOwner = new Map(icons.flatMap((i) => i.meta.aliases.map((a) => [a, i.meta.name] as const)));

const problems: string[] = [];
const seen = new Map<string, string>();
for (const [slug, names] of Object.entries(roadmap.categories)) {
  if (!categories.some((c) => c.slug === slug)) problems.push(`unknown category "${slug}"`);
  for (const name of names) {
    if (!NAME_PATTERN.test(name)) problems.push(`${slug}: "${name}" is not a valid icon name`);
    if (seen.has(name)) problems.push(`"${name}" is planned in both ${seen.get(name)} and ${slug}`);
    seen.set(name, slug);
  }
}

const rows: string[] = [];
let plannedTotal = 0;
let publishedTotal = 0;
const sections: string[] = [];
for (const category of categories) {
  // A published icon counts only in its own category, even if planned elsewhere.
  const planned = (roadmap.categories[category.slug] ?? []).filter((n) => !published.has(n) || published.get(n)!.category === category.slug);
  const inCategory = icons.filter((i) => i.meta.category === category.slug).map((i) => i.meta.name);
  const concepts = [...new Set([...planned, ...inCategory])];
  const done = concepts.filter((n) => published.has(n));
  const coveredByAlias = concepts.filter((n) => !published.has(n) && aliasOwner.has(n));
  const todo = concepts.filter((n) => !published.has(n) && !aliasOwner.has(n));
  plannedTotal += concepts.length - coveredByAlias.length;
  publishedTotal += done.length;
  const pct = concepts.length ? Math.round((done.length / (concepts.length - coveredByAlias.length)) * 100) : 0;
  rows.push(`| ${category.name} | ${done.length} | ${todo.length} | ${pct}% |`);
  sections.push(
    `### ${category.name}\n\n` +
      `**Published (${done.length}):** ${done.map((n) => `\`${n}\``).join(", ") || "—"}\n\n` +
      `**Planned (${todo.length}):** ${todo.map((n) => `\`${n}\``).join(", ") || "—"}\n` +
      (coveredByAlias.length
        ? `\n**Covered by an existing icon's alias (no new artwork):** ${coveredByAlias.map((n) => `\`${n}\` → \`${aliasOwner.get(n)}\``).join(", ")}\n`
        : ""),
  );
}

const report = `# Catalog roadmap

> Generated by \`pnpm icons:roadmap\` from \`assets/roadmap.json\` and \`assets/source/\`. Do not edit by hand.

Published icons are complete Outline + Filled pairs that pass validation and visual review. Planned concepts are
**not** published and are never shown on the website or counted in statistics.

- Published concepts: **${publishedTotal}** (${publishedTotal * 2} SVG assets)
- Concepts in this roadmap: **${plannedTotal}**
- Long-term target: 3,000–5,000 concepts. The roadmap grows category by category as research expands each list.

| Category | Published | Planned | Progress |
| --- | ---: | ---: | ---: |
${rows.join("\n")}

## Expansion process

For every batch: research the category, add concepts here, draw both variants following
\`docs/icon-design-spec.md\`, run \`pnpm icons:validate\`, review \`pnpm icons:sheet\`, accept the renders with
\`pnpm icons:visual --update\`, run \`pnpm icons:build\` and the tests, then add release notes to
\`assets/releases.json\`.

## By category

${sections.join("\n")}`;

fs.writeFileSync(path.join(ROOT, "docs", "catalog-roadmap.md"), report);
console.log(`Published ${publishedTotal} of ${plannedTotal} roadmap concepts. Report: docs/catalog-roadmap.md`);
if (problems.length) {
  for (const p of problems) console.error(`error  ${p}`);
  process.exit(1);
}

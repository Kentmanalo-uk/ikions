/**
 * `pnpm icons:plan` — sync the batch manifest and print/write the progress
 * report (docs/expansion-progress.md). Only icons whose outline and filled
 * files exist and pass validation count as complete.
 */
import fs from "node:fs";
import path from "node:path";
import { loadCatalog } from "../catalog.ts";
import { ROOT } from "../paths.ts";
import { loadPlan, syncBatches } from "../plan.ts";
import { validateCatalog } from "../validate.ts";

const batches = syncBatches();
const { generated, concepts, rejected } = loadPlan();
const catalog = loadCatalog();
const issues = validateCatalog(catalog).filter((i) => i.severity === "error");
const failing = new Set(issues.map((i) => i.icon));
const valid = catalog.icons.filter((i) => !failing.has(i.meta.name)).map((i) => i.meta.name);
const validSet = new Set(valid);

const plannedTotal = new Set([...validSet, ...generated.map((g) => g.name), ...concepts.map((c) => c.name)]).size;
const genDone = generated.filter((g) => validSet.has(g.name)).length;
const handDone = concepts.filter((c) => validSet.has(c.name)).length;

const rows = batches.map((b) => {
  const done = b.names.filter((n) => validSet.has(n)).length;
  const status = done === b.names.length ? "done" : done > 0 ? "partial" : "todo";
  return { ...b, done, status };
});

const report = `# Icon library expansion — progress

> Generated by \`pnpm icons:plan\`. An icon counts as complete only when both variants exist and pass validation.

| Measure | Count |
| --- | ---: |
| Published icons passing validation | **${valid.length}** |
| Outline SVG assets | ${valid.length} |
| Filled SVG assets | ${valid.length} |
| Icons with validation errors (need review) | ${failing.size} |
| Generated family icons complete / planned | ${genDone} / ${generated.length} |
| Hand-drawn concepts complete / planned | ${handDone} / ${concepts.length} |
| Total planned unique concepts | ${plannedTotal} |
| Remaining to reach the plan | ${Math.max(0, plannedTotal - valid.length)} |

Rejected from the hand-drawn list (brand-derived or second drawings of an existing concept): ${rejected.length ? rejected.map((r) => `\`${r}\``).join(", ") : "none"}.

## Batches

| Batch | Category | Done | Status |
| --- | --- | ---: | --- |
${rows.map((r) => `| ${r.id} | ${r.category} | ${r.done}/${r.names.length} | ${r.status} |`).join("\n")}
`;

fs.writeFileSync(path.join(ROOT, "docs", "expansion-progress.md"), report);
console.log(
  `valid ${valid.length} · failing ${failing.size} · generated ${genDone}/${generated.length} · hand-drawn ${handDone}/${concepts.length} · planned total ${plannedTotal} · batches ${batches.length} (${rows.filter((r) => r.status === "done").length} done)`,
);
